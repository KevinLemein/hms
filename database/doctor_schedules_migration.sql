--
-- MediCare: doctor working hours and time off
--
-- Run once against the existing database (restored from medicare.sql), AFTER
-- that dump:
--
--     psql -U postgres -d medicare -f database/doctor_schedules_migration.sql
--
-- It is safe to re-run (everything is IF NOT EXISTS). The backend runs with
-- spring.jpa.hibernate.ddl-auto=update and would create these two tables
-- itself on first start; running this script first just makes the schema
-- explicit, adds the constraints and gives the same table/index names
-- Hibernate uses, so nothing is created twice.
--
-- This is the only schema change needed for the appointment/slot features:
--   * patient booking, rescheduling and cancelling, the doctors list and the
--     free-slot list reuse the existing `appointments`, `users` and
--     `patients` tables unchanged (no new columns, same status values);
--   * a doctor with no rows in doctor_schedules keeps using the clinic-wide
--     default hours (app.clinic.opening-hour / closing-hour / slot-minutes),
--     so existing doctors need no data migration.
--

BEGIN;

--
-- Weekly working hours. A doctor may have several blocks per day (a gap
-- between two blocks is a break). day_of_week is ISO: 1 = Monday ... 7 = Sunday.
--
CREATE TABLE IF NOT EXISTS public.doctor_schedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id bigint NOT NULL,
    day_of_week integer NOT NULL,
    start_time time(6) without time zone NOT NULL,
    end_time time(6) without time zone NOT NULL,
    slot_minutes integer NOT NULL,
    CONSTRAINT fk_doctor_schedules_doctor FOREIGN KEY (doctor_id) REFERENCES public.users(id) ON DELETE CASCADE,
    CONSTRAINT doctor_schedules_day_check CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT doctor_schedules_time_check CHECK (start_time < end_time),
    CONSTRAINT doctor_schedules_slot_check CHECK (slot_minutes BETWEEN 5 AND 240)
);

ALTER TABLE public.doctor_schedules OWNER TO postgres;

CREATE INDEX IF NOT EXISTS idx_doctor_schedules_doctor ON public.doctor_schedules USING btree (doctor_id);

--
-- Whole days (inclusive) on which a doctor takes no appointments.
--
CREATE TABLE IF NOT EXISTS public.doctor_time_off (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id bigint NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    reason character varying(255),
    created_at timestamp(6) without time zone NOT NULL DEFAULT now(),
    CONSTRAINT fk_doctor_time_off_doctor FOREIGN KEY (doctor_id) REFERENCES public.users(id) ON DELETE CASCADE,
    CONSTRAINT doctor_time_off_dates_check CHECK (start_date <= end_date)
);

ALTER TABLE public.doctor_time_off OWNER TO postgres;

CREATE INDEX IF NOT EXISTS idx_doctor_time_off_doctor ON public.doctor_time_off USING btree (doctor_id);

--
-- Speeds up the slot lookup and the double-booking check, which both filter
-- appointments by doctor and date/time.
--
CREATE INDEX IF NOT EXISTS idx_appointments_doctor_datetime
    ON public.appointments USING btree (doctor_id, appointment_date_time);

COMMIT;

